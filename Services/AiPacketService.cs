using System.Text;
using JobHuntHQ.Models;

namespace JobHuntHQ.Services;

/// <summary>
/// Builds the bring-your-own-AI packet (M4): a self-contained Markdown
/// document a user hands to their own AI assistant. The packet carries an
/// instruction preamble (use only the facts in the packet, never invent
/// experience or answers, stop and ask before any submission), the posting,
/// the fit check, the user's search profile and standing answers, and the
/// chosen resume's metadata. JobHunt HQ itself never submits anything — the
/// user's own AI and the user do that, outside this app.
/// </summary>
public class AiPacketService
{
    public string BuildMarkdown(JobApplication application, SearchProfile? profile, ResumeVersion? resume)
    {
        var sb = new StringBuilder();

        sb.AppendLine($"# Job application packet — {application.Company} — {application.RoleTitle}");
        sb.AppendLine();
        sb.AppendLine("Generated by JobHunt HQ for use with your own AI assistant.");
        sb.AppendLine();

        sb.AppendLine("## Instructions for the AI assistant");
        sb.AppendLine();
        sb.AppendLine("- Help prepare this application using ONLY the facts in this packet. Never invent experience, credentials, employers, dates, or answers.");
        sb.AppendLine("- Where the packet doesn't say something, say so and ask the user — do not guess or fill gaps with plausible-sounding details.");
        sb.AppendLine("- Use the standing answers verbatim where they fit a question; flag any question they don't cover instead of improvising.");
        sb.AppendLine("- Respect the fit check below: if the verdict is Blocked, tell the user why before doing any preparation work.");
        sb.AppendLine("- Stop and ask the user before any final submission. The user reviews and submits everything themselves.");
        sb.AppendLine();

        sb.AppendLine("## The posting");
        sb.AppendLine();
        sb.AppendLine($"- Company: {application.Company}");
        sb.AppendLine($"- Role: {application.RoleTitle}");
        var postingUrl = application.PostingUrl ?? application.Url;
        if (!string.IsNullOrWhiteSpace(postingUrl))
        {
            sb.AppendLine($"- Posting URL: {postingUrl}");
        }
        if (!string.IsNullOrWhiteSpace(application.Location))
        {
            sb.AppendLine($"- Location: {application.Location}");
        }
        if (application.PayMin.HasValue || application.PayMax.HasValue)
        {
            sb.AppendLine($"- Pay listed in posting: {Money(application.PayMin)} – {Money(application.PayMax)}");
        }
        sb.AppendLine();
        sb.AppendLine("### Posting text");
        sb.AppendLine();
        sb.AppendLine(string.IsNullOrWhiteSpace(application.PostingText)
            ? "(No posting text was captured — work from the title and URL, and ask the user for the full posting before drafting anything.)"
            : application.PostingText.Trim());
        sb.AppendLine();

        sb.AppendLine("## Fit check");
        sb.AppendLine();
        sb.AppendLine($"Verdict: {application.FitVerdict ?? FitCheckService.VerdictNotChecked}");
        if (!string.IsNullOrWhiteSpace(application.FitReasons))
        {
            foreach (var line in application.FitReasons.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                sb.AppendLine($"- {line}");
            }
        }
        sb.AppendLine();

        sb.AppendLine("## My search profile");
        sb.AppendLine();
        if (profile is null)
        {
            sb.AppendLine("(No search profile saved yet.)");
        }
        else
        {
            AppendField(sb, "Target roles", profile.TargetRoles);
            AppendField(sb, "Remote preference", profile.RemotePreference);
            if (profile.PayFloor.HasValue)
            {
                sb.AppendLine($"- Pay floor: {Money(profile.PayFloor)}");
            }
            AppendField(sb, "Must-haves", profile.MustHaves);
            AppendField(sb, "Deal-breakers", profile.DealBreakers);
            AppendField(sb, "Skip companies", profile.SkipCompanies);
            sb.AppendLine();
            sb.AppendLine("### My standing answers");
            sb.AppendLine();
            sb.AppendLine(string.IsNullOrWhiteSpace(profile.StandingAnswers)
                ? "(None saved.)"
                : profile.StandingAnswers.Trim());
        }
        sb.AppendLine();

        sb.AppendLine("## Resume");
        sb.AppendLine();
        if (resume is null)
        {
            sb.AppendLine("(No resume version saved — ask the user which resume to use.)");
        }
        else
        {
            sb.AppendLine($"- Version: {resume.Name}");
            sb.AppendLine(resume.FileName is not null
                ? $"- File uploaded: {resume.FileName}"
                : "- File uploaded: none (metadata only)");
            if (!string.IsNullOrWhiteSpace(resume.Notes))
            {
                sb.AppendLine($"- Notes: {resume.Notes}");
            }
        }
        sb.AppendLine();

        sb.AppendLine("## Where this application stands");
        sb.AppendLine();
        sb.AppendLine($"- Status: {application.Status}");
        sb.AppendLine($"- Date saved: {application.DateSaved:yyyy-MM-dd}");
        if (application.DateApplied.HasValue)
        {
            sb.AppendLine($"- Date applied: {application.DateApplied.Value:yyyy-MM-dd}");
        }
        if (!string.IsNullOrWhiteSpace(application.NextAction))
        {
            sb.AppendLine(application.NextActionDue.HasValue
                ? $"- Next action: {application.NextAction} (due {application.NextActionDue.Value:yyyy-MM-dd})"
                : $"- Next action: {application.NextAction}");
        }
        if (!string.IsNullOrWhiteSpace(application.Notes))
        {
            sb.AppendLine();
            sb.AppendLine("### My notes");
            sb.AppendLine();
            sb.AppendLine(application.Notes.Trim());
        }

        return sb.ToString();
    }

    private static void AppendField(StringBuilder sb, string label, string? value)
    {
        if (!string.IsNullOrWhiteSpace(value))
        {
            sb.AppendLine($"- {label}: {value.Trim()}");
        }
    }

    private static string Money(int? value) =>
        value.HasValue ? "$" + value.Value.ToString("N0") : "—";
}
